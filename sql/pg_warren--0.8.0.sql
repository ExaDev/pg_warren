                ARRAY(SELECT jsonb_array_elements_text(step -> 'filter')) END,
            coalesce((step ->> 'min_hops')::int, 1),
            (step ->> 'max_hops')::int)::warren.step;
    END LOOP;
    RETURN result;
END
