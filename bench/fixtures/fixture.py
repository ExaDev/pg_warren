"""A fixture: the tables a generator emits plus the ground truth its
assertions need, and how a fixture is written to disk for psql to load."""

import csv
import json
from dataclasses import dataclass
from pathlib import Path

import numpy as np


@dataclass(frozen=True)
class Column:
    name: str
    sql_type: str
    values: object  # a sequence or numpy array, one entry per row


@dataclass(frozen=True)
class Table:
    name: str
    columns: tuple[Column, ...]

    def __post_init__(self):
        lengths = {len(c.values) for c in self.columns}
        if len(lengths) > 1:
            raise ValueError(f"table {self.name}: columns differ in length {sorted(lengths)}")

    @classmethod
    def of(cls, name, **columns):
        """`Table.of("edges", src=("bigint", array), ...)`, columns in order."""
        return cls(name, tuple(Column(n, t, v) for n, (t, v) in columns.items()))

    def column(self, name):
        for c in self.columns:
            if c.name == name:
                return np.asarray(c.values)
        raise KeyError(f"table {self.name} has no column {name}")

    def __len__(self):
        return len(self.columns[0].values) if self.columns else 0


@dataclass(frozen=True)
class Fixture:
    name: str
    tables: tuple[Table, ...]
    truth: dict

    def table(self, name):
        for t in self.tables:
            if t.name == name:
                return t
        raise KeyError(f"fixture {self.name} has no table {name}")

    def write(self, directory):
        """Writes `<table>.csv` per table, `truth.json`, `truth.csv` and
        `load.sql`, a psql script that creates and loads every table plus a
        `truth (key, value jsonb)` table. Run it with psql's working
        directory set to `directory`: `\\copy` paths are relative to it."""
        directory = Path(directory)
        directory.mkdir(parents=True, exist_ok=True)
        for table in self.tables:
            _write_csv(directory / f"{table.name}.csv", table)
        (directory / "truth.json").write_text(json.dumps(self.truth, indent=1, sort_keys=False) + "\n")
        with open(directory / "truth.csv", "w", newline="") as f:
            out = csv.writer(f, lineterminator="\n")
            out.writerow(["key", "value"])
            for key, value in self.truth.items():
                out.writerow([key, json.dumps(value)])
        (directory / "load.sql").write_text(self._load_script())

    def _load_script(self):
        lines = [f"-- fixture {self.name}: generated by bench/generate.py"]
        for table in self.tables:
            columns = ", ".join(f"{c.name} {c.sql_type}" for c in table.columns)
            lines.append(f"CREATE TABLE {table.name} ({columns});")
            lines.append(_copy(table.name))
        lines.append("CREATE TABLE truth (key text PRIMARY KEY, value jsonb NOT NULL);")
        lines.append(_copy("truth"))
        lines.append("ANALYZE;")
        return "\n".join(lines) + "\n"


def _copy(table):
    return f"\\copy {table} FROM '{table}.csv' WITH (FORMAT csv, HEADER true)"


def _write_csv(path, table):
    with open(path, "w", newline="") as f:
        out = csv.writer(f, lineterminator="\n")
        out.writerow([c.name for c in table.columns])
        cells = [[_cell(v) for v in c.values] for c in table.columns]
        out.writerows(zip(*cells))


def _cell(value):
    if value is None:
        return ""
    if isinstance(value, (bool, np.bool_)):
        return "t" if value else "f"
    if isinstance(value, np.ndarray):
        return "{" + ",".join(_cell(v) for v in value) + "}"
    if isinstance(value, np.float32):
        return format(float(value), ".9g")
    if isinstance(value, (float, np.floating)):
        return repr(float(value))
    if isinstance(value, np.integer):
        return str(int(value))
    return str(value)
