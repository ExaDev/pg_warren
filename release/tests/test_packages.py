"""Tests of release/packages.py, which builds the .deb packages of the apt
repository and the tarballs (CONTRIBUTING.md, "Packages"): Debian
versions per distribution, the generated debian/changelog, the pgrx a
source pins, and the tarball laid out from a built package."""

import re
import shutil
import subprocess
import tarfile
from pathlib import Path

import pytest

from packages import (DISTRIBUTIONS, MAJORS, PackagingError, changelog, debian_version, distribution,
                      pgrx_version, postgres_image, tarball, tarball_name)

needs_dpkg = pytest.mark.skipif(shutil.which("dpkg-deb") is None or shutil.which("dpkg-parsechangelog") is None,
                                reason="needs dpkg-deb and dpkg-parsechangelog (dpkg-dev)")

LOCK = """# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "pgrx"
version = "0.19.3"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "pgrx-macros"
version = "0.19.3"
"""


def test_each_distribution_is_built_in_its_own_image_pinned_by_digest():
    images = {d.codename: d.image for d in DISTRIBUTIONS}
    assert {codename: image.partition("@")[0] for codename, image in images.items()} == {
        "bookworm": "debian:bookworm",
        "trixie": "debian:trixie",
        "jammy": "ubuntu:22.04",
        "noble": "ubuntu:24.04",
    }
    assert all(re.fullmatch(r"[a-z]+:[0-9a-z.]+@sha256:[0-9a-f]{64}", image) for image in images.values())


@pytest.mark.parametrize("major", MAJORS)
@pytest.mark.parametrize("codename", ["bookworm", "trixie"])
def test_the_image_s_base_is_pgdg_s_postgres_pinned_by_digest(major, codename):
    assert re.fullmatch(rf"postgres:{major}-{codename}@sha256:[0-9a-f]{{64}}", postgres_image(major, codename))


def test_there_is_no_postgres_image_for_ubuntu():
    with pytest.raises(PackagingError, match="noble"):
        postgres_image("16", "noble")


def test_an_unknown_distribution_is_refused():
    with pytest.raises(PackagingError, match="sid"):
        distribution("sid")


def test_the_debian_version_sorts_below_an_official_build_of_the_same_release():
    # A tilde sorts before anything, so PGDG's 0.7.0-1.pgdg120+1 would win.
    assert debian_version("0.7.0", "bookworm") == "0.7.0-1~deb12"
    assert debian_version("0.7.0", "trixie") == "0.7.0-1~deb13"
    assert debian_version("0.7.0", "jammy") == "0.7.0-1~ubuntu22.04"
    assert debian_version("0.7.0", "noble") == "0.7.0-1~ubuntu24.04"


def test_versions_differ_between_distributions_so_one_pool_holds_them_all():
    versions = {debian_version("1.2.3", d.codename) for d in DISTRIBUTIONS}
    assert len(versions) == len(DISTRIBUTIONS)


def test_only_a_release_version_is_packaged():
    with pytest.raises(PackagingError, match="X.Y.Z"):
        debian_version("0.7.0-rc.1", "bookworm")


def test_the_changelog_names_the_release_and_dates_it_by_its_commit():
    text = changelog("0.7.0", "noble", 1793059200)
    first, *_, last = text.rstrip("\n").splitlines()
    assert first == "pg-warren (0.7.0-1~ubuntu24.04) noble; urgency=medium"
    assert "https://github.com/ExaDev/pg_warren/releases/tag/v0.7.0" in text
    assert last.startswith(" -- ") and last.endswith(">  Tue, 27 Oct 2026 00:00:00 +0000")


@needs_dpkg
def test_dpkg_parses_the_changelog(tmp_path):
    (tmp_path / "debian").mkdir()
    (tmp_path / "debian" / "changelog").write_text(changelog("0.7.0", "bookworm", 0))
    parsed = subprocess.run(["dpkg-parsechangelog", "-l", "debian/changelog", "-SVersion"], cwd=tmp_path,
                            capture_output=True, text=True, check=True)
    assert parsed.stdout.strip() == "0.7.0-1~deb12"


def test_the_pgrx_a_source_pins_is_read_from_its_lock_file():
    assert pgrx_version(LOCK) == "0.19.3"


def test_a_lock_file_without_pgrx_is_refused():
    with pytest.raises(PackagingError, match="pgrx"):
        pgrx_version('version = 4\n[[package]]\nname = "pgrx-macros"\nversion = "0.19.3"\n')


def fake_deb(directory, major, version="0.7.0-1~ubuntu22.04", arch="amd64"):
    """A package with the files a pg_warren package installs."""
    root = directory / "root"
    lib = root / f"usr/lib/postgresql/{major}/lib"
    extension = root / f"usr/share/postgresql/{major}/extension"
    doc = root / f"usr/share/doc/postgresql-{major}-pg-warren"
    for path in (lib, extension, doc, root / "DEBIAN"):
        path.mkdir(parents=True)
    (lib / "pg_warren.so").write_bytes(b"\x7fELF")
    (extension / "pg_warren.control").write_text("default_version = '0.7.0'\n")
    (extension / "pg_warren--0.7.0.sql").write_text("CREATE SCHEMA warren;\n")
    (extension / "pg_warren--0.6.0--0.7.0.sql").write_text("SELECT 1;\n")
    (doc / "copyright").write_text("Apache-2.0\n")
    (root / "DEBIAN" / "control").write_text(
        f"Package: postgresql-{major}-pg-warren\nVersion: {version}\nArchitecture: {arch}\n"
        "Maintainer: Test <test@example.invalid>\nDescription: test\n")
    deb = directory / f"postgresql-{major}-pg-warren_{version}_{arch}.deb"
    subprocess.run(["dpkg-deb", "--root-owner-group", "--build", root, deb], check=True, capture_output=True)
    return deb


def test_the_tarball_is_named_for_its_release_major_and_machine():
    assert tarball_name("0.7.0", "16", "amd64") == "pg_warren-0.7.0-pg16-linux-x86_64"
    assert tarball_name("0.7.0", "18", "arm64") == "pg_warren-0.7.0-pg18-linux-aarch64"


@needs_dpkg
def test_the_tarball_is_laid_out_for_pg_config(tmp_path):
    deb = fake_deb(tmp_path, "16")
    out = tmp_path / "out"
    out.mkdir()
    made = tarball(deb, out, epoch=0)
    assert made == out / "pg_warren-0.7.0-pg16-linux-x86_64.tar.gz"
    with tarfile.open(made) as archive:
        members = {m.name: m for m in archive.getmembers()}
        prefix = "pg_warren-0.7.0-pg16-linux-x86_64"
        assert set(members) == {
            prefix, f"{prefix}/pkglibdir", f"{prefix}/sharedir", f"{prefix}/sharedir/extension",
            f"{prefix}/pkglibdir/pg_warren.so",
            f"{prefix}/sharedir/extension/pg_warren.control",
            f"{prefix}/sharedir/extension/pg_warren--0.7.0.sql",
            f"{prefix}/sharedir/extension/pg_warren--0.6.0--0.7.0.sql",
            f"{prefix}/LICENSE", f"{prefix}/NOTICE", f"{prefix}/INSTALL",
        }
        assert all(m.uid == 0 and m.gid == 0 and m.mtime == 0 for m in members.values())
        install = archive.extractfile(f"{prefix}/INSTALL").read().decode()
        assert '"$(pg_config --pkglibdir)"' in install and '"$(pg_config --sharedir)/extension"' in install
        assert "shared_preload_libraries" in install
        assert "Built on Ubuntu 22.04" in install


@needs_dpkg
def test_the_same_package_gives_the_same_tarball(tmp_path):
    deb = fake_deb(tmp_path, "16")
    first, second = tmp_path / "a", tmp_path / "b"
    first.mkdir()
    second.mkdir()
    one = tarball(deb, first, epoch=1700000000).read_bytes()
    assert tarball(deb, second, epoch=1700000000).read_bytes() == one


@needs_dpkg
def test_a_package_without_the_library_is_refused(tmp_path):
    deb = fake_deb(tmp_path, "17")
    root = tmp_path / "root"
    (root / "usr/lib/postgresql/17/lib/pg_warren.so").unlink()
    subprocess.run(["dpkg-deb", "--root-owner-group", "--build", root, deb], check=True, capture_output=True)
    with pytest.raises(PackagingError, match="pg_warren.so"):
        tarball(deb, tmp_path, epoch=0)


@needs_dpkg
def test_tarball_entries_are_ordered(tmp_path):
    deb = fake_deb(tmp_path, "15", arch="arm64")
    made = tarball(deb, tmp_path, epoch=0)
    with tarfile.open(made) as archive:
        names = archive.getnames()
    assert names == sorted(names)
    assert Path(made).name == "pg_warren-0.7.0-pg15-linux-aarch64.tar.gz"
